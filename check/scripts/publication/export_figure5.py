#!/usr/bin/env python3
"""Publish the audited matched rerun preview using Figure 5's existing layout."""
import argparse
import json
from pathlib import Path

import numpy as np
from plot_style import render_time_selection, METHODS, HORIZON


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True)
    parser.add_argument('--paper', type=Path, required=True)
    args = parser.parse_args()
    (args.paper / "resources/practical-evaluation").mkdir(parents=True, exist_ok=True)
    summary = json.loads((args.input / 'summary.json').read_text())
    rows = json.loads((args.input / 'trajectories.json').read_text())
    curves = {}
    for item in summary['summary']:
        z, n = item['z'], item['n']
        for method in METHODS:
            if method not in item.get("methods", METHODS):
                continue
            group = [r for r in rows if r['z'] == z and r['method'] == method]
            assert len(group) == n
            if not n:
                curves[z, method] = []
                continue
            hits = np.sort([r['first_seconds'] for r in group if r['terminal_hit']])
            grid = np.unique(np.r_[1, hits[hits > 1], HORIZON])
            percentages = 100 * np.searchsorted(hits, grid, side='right') / n
            assert len(hits) == item['hits'][method]
            assert np.all(np.diff(percentages) >= 0)
            curves[z, method] = list(zip(grid, percentages))

    def save(name, lines):
        text = ('% Generated by check/scripts/publication/export_figure5.py.\n'
                f'% Source: {args.input.resolve()}\n'
                f'% Snapshot: {summary["created_at"]}\n' + '\n'.join(lines) + '\n')
        (args.paper / 'resources/practical-evaluation' / name).write_text(text)

    render_time_selection(curves, summary['summary'], save)


if __name__ == '__main__':
    main()
