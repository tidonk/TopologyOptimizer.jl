#!/usr/bin/env python3
"""Export Figure 6 from completed sequential-heuristic warmstart reruns."""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
from plot_style import STYLE, coordinates, tikz_figure, HORIZON, METHODS


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path, required=True)
    parser.add_argument('--paper', type=Path, required=True)
    parser.add_argument('--diagnostics', type=Path, required=True)
    args = parser.parse_args()
    (args.paper / "resources/practical-evaluation").mkdir(parents=True, exist_ok=True)
    args.diagnostics.mkdir(parents=True, exist_ok=True)
    source = args.input / 'trajectories.json'
    rows = json.loads(source.read_text())
    lookup = {(r['case'], r['z'], r['method']): r for r in rows}
    cases = sorted({r['case'] for r in rows})
    assert len(cases) == 130
    maximum = max(z for z in range(1, 6)
                  if all((c, zz, m) in lookup for c in cases
                         for zz in range(1, z + 1) for m in METHODS))
    assert maximum >= 4
    zero = {}
    for case in cases:
        row = lookup[case, 1, 'warmstart']
        zero[case] = row['precise_endpoints'][0][1]
    denominator_shift = 1e-4
    assert all(zero[c] >= 0 for c in cases)
    achieved = np.zeros((len(cases), maximum + 1))
    possible = np.zeros_like(achieved)
    for i, case in enumerate(cases):
        denominator = zero[case] + denominator_shift
        for z in range(1, maximum + 1):
            row = lookup[case, z, 'warmstart']
            primal, dual = row['objective'], row['lower_bound']
            assert np.isfinite(primal) and dual is not None and np.isfinite(dual)
            assert dual <= primal + .01, (case, z, primal, dual)
            achieved[i, z] = 100 * (zero[case] - primal) / denominator
            possible[i, z] = max(achieved[i, z], 100 * (zero[case] - dual) / denominator)
            if zero[case] == 0:
                assert achieved[i, z] == possible[i, z] == 0, (case, z)
    summaries = {name: dict(achieved=reducer(achieved).tolist(),
                            upper_bound=reducer(possible).tolist())
                 for name, reducer in [('mean', lambda x: x.mean(axis=0)),
                                       ('median', lambda x: np.median(x, axis=0))]}
    header = ('% Generated by check/scripts/publication/export_figure6.py.\n'
              f'% Source: {source.resolve()}\n'
              f'% Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()}\n'
              '% Absolute reduction threshold: 0.0001; six-hour cutoff before SCOPF removal.\n')
    def save(name, text):
        (args.paper / 'resources/practical-evaluation' / name).write_text(header + text)
    save('cumulative-savings.tikz.tex', tikz_figure(summaries, len(cases)))

    lines = [rf'\def\stepwiseCommonN{{{len(cases)}}}',
             rf'\def\stepwiseFinalN{{{len(cases)}}}',
             r'\ifdefined\practicalFigureWidth\else',
             r'\newlength{\practicalFigureWidth}\setlength{\practicalFigureWidth}{\linewidth}\fi',
             r'\begin{tikzpicture}[baseline=(current axis.north)]',
             r'\definecolor{practicalseq}{HTML}{DC267F}',
             r'\begin{axis}[scale only axis,width=0.415\practicalFigureWidth,height=0.18\practicalFigureWidth,',
             r'xmode=log,xmin=1,xmax=21600,ymin=0,ymax=100,ytick={0,25,50,75,100},',
             r'xtick={1,10,100,1000,10000},xticklabels={$10^0$,$10^1$,$10^2$,$10^3$,$10^4$},xminorticks=false,',
             r'xlabel={Solver time (s)},ylabel={Instances improving (\%)},',
             STYLE + ']']
    timing_summary, timings = [], []
    for z in range(1, maximum + 1):
        hits = []
        for case in cases:
            reference = zero[case] if z == 1 else min(lookup[case, z - 1, m]['objective'] for m in METHODS)
            row = lookup[case, z, 'warmstart']
            target = reference - 1e-4
            hit = row['objective'] <= target
            events = [t for t, p in row['pairs'] if t <= HORIZON and p <= target] if hit else []
            assert bool(events) == hit, (case, z, 'Target attainment missing')
            first = max(0., min(events) - row['scopf_seconds']) if events else None
            if first is not None:
                hits.append(first)
            timings.append(dict(case=case, z=z, reference=reference,
                                first_seconds=first, terminal_hit=hit))
        hits = np.sort(hits)
        grid = np.unique(np.r_[1, hits[hits > 1], HORIZON])
        percentages = 100 * np.searchsorted(hits, grid, side='right') / len(cases)
        assert np.all(np.diff(percentages) >= 0)
        lines.append(rf'\addplot[const plot,no marks,color=practicalseq,solid,line width=0.9pt] coordinates {{{coordinates(grid, percentages)}}};')
        end = percentages[-1]
        timing_summary.append(dict(z=z, n=len(cases), hits=len(hits), percent=float(end),
                                   by_ten_minutes=int((hits <= 600).sum())))
    # Place labels near each endpoint, moving them apart when necessary.
    labels = sorted(timing_summary, key=lambda r: r['percent'])
    positions = []
    for r in labels:
        positions.append(max(r['percent'], positions[-1] + 8 if positions else 0))
    if positions[-1] > 97:
        positions = [p - positions[-1] + 97 for p in positions]
    for r, label_y in zip(labels, positions):
        end, z = r['percent'], r['z']
        if abs(label_y - end) > 1e-7:
            lines.append(rf'\draw[practicalseq,line width=0.4pt] (axis description cs:1,{end/100:.10g}) -- (axis description cs:1.025,{label_y/100:.10g});')
        lines.append(rf'\node[anchor=west,font=\footnotesize,inner sep=1pt] at (axis description cs:1.03,{label_y/100:.10g}) {{$Z={z}$}};')
    lines.extend([r'\end{axis}', r'\end{tikzpicture}'])
    save('stepwise-improvements.tikz.tex', '\n'.join(lines) + '\n')
    report = dict(maximum=maximum, n=len(cases), savings_n=len(cases),
                  denominator_shift=denominator_shift,
                  zero_scopf_cases=[c for c in cases if zero[c] == 0],
                  savings=summaries, improvement_times=timing_summary,
                  reference='Best objective across all five configurations at Z-1, SCOPF at Z=1',
                  clock='Solver time excluding SCOPF; cutoff includes SCOPF',
                  absolute_threshold=1e-4, rows=timings)
    (args.diagnostics / 'figure6-summary.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps({k:v for k,v in report.items() if k != 'rows'}, indent=2))


if __name__ == '__main__':
    main()
